# ---------------------------------------------------------
# صندوق السؤال والبحث (يعرض التفاصيل الكاملة)
# ---------------------------------------------------------
query = st.text_area("اكتب سؤالك التاريخي:", placeholder="مثال: احكي لي عن كليوباترا أو رمسيس...")

if st.button("🔍 ابحث واشرح"):
    if query.strip():
        matched_king = None
        for king in detailed_stories:
            if any(part.lower() in query.lower() for part in king.split()):
                matched_king = king
                break
        
        if matched_king and detailed_stories[matched_king].strip():
            st.subheader(f"📜 قصة {matched_king} (بالتفصيل)")
            st.write(detailed_stories[matched_king])
        else:
            st.info("💡 عذراً، لم تقمي بإضافة القصة التفصيلية لهذا الملك بعد في قسم القصص التفصيلية!")

