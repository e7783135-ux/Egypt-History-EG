with col1:
    if st.button("👑 ملوك وأباطرة"):
        st.success("إليك القائمة المختصرة للملوك بالأسفل للاطلاع السريع!")

with col2:
    if st.button("⚔️ معارك حاسمة"):
        st.info("استعرض أشهر المعارك التاريخية.")

